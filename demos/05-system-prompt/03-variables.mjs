// 5.2 变量与插值：取值时机、三种错误、值不会被二次展开、孤立的 {{ 是字面文本。
//   node demos/05-system-prompt/03-variables.mjs

import { 提示注册表 } from '../../src/system-prompt.ts'

/**
 * 跑一次装配，成功就打印结果，失败就打印错误。
 * @param {string} 标题 - 这一格演示什么。
 * @param {(提示: 提示注册表) => void} 装配 - 往注册表里塞东西。
 */
const 试 = (标题, 装配) => {
  console.log(`\n── ${标题} ──`)
  const 提示 = new 提示注册表()
  try {
    装配(提示)
    console.log(`  ✅ ${提示.组装()}`)
  } catch (错误) {
    console.log(`  ❌ ${错误.message}`)
  }
}

试('① 正常插值', 提示 => {
  提示.变量('cwd', () => '/home/me/项目')
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '工作目录是 {{cwd}}。' })
})

试('② 变量名拼错了', 提示 => {
  提示.变量('cwd', () => '/home/me/项目')
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '工作目录是 {{cdw}}。' })
})

试('③ 变量注册了，但这次取不到值', 提示 => {
  提示.变量('git_branch', () => undefined)   // 比如：这个目录不是 git 仓库
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '当前分支 {{git_branch}}。' })
})

试('④ 引用写坏了', 提示 => {
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '工作目录是 {{ cwd }}。' })
})

试('⑤ 孤零零的 {{ 是普通文字，不报错', 提示 => {
  提示.注册({ 名字: 'a', 顺序: 0, 文本: 'Jinja 模板里的变量写成 {{ 加名字。' })
})

试('⑥ 变量的值里含 {{...}}，不会被二次展开', 提示 => {
  // 假设用户的目录名字就叫这个——一个恶意或者只是手滑的目录名。
  提示.变量('cwd', () => '/tmp/{{secret}}')
  提示.变量('secret', () => '不该被读到的东西')
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '工作目录是 {{cwd}}。' })
})

试('⑦ 同一次组装里，两段读到同一个值', 提示 => {
  let 第几次 = 0
  提示.变量('n', () => String(++第几次))
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '第一段看到 {{n}}。' })
  提示.注册({ 名字: 'b', 顺序: 1, 文本: '第二段看到 {{n}}。' })
})

console.log('\n── ⑧ 取值发生在组装时，不是注册时 ──')
{
  const 提示 = new 提示注册表()
  let 当前目录 = '/一开始的目录'
  提示.变量('cwd', () => 当前目录)
  提示.注册({ 名字: 'a', 顺序: 0, 文本: '工作目录是 {{cwd}}。' })
  console.log(`  组装第一次：${提示.组装()}`)
  当前目录 = '/后来换了的目录'
  console.log(`  组装第二次：${提示.组装()}`)
}
